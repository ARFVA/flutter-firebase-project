import 'package:flutter/material.dart';
import 'package:get/get.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:cloud_firestore/cloud_firestore.dart';
import 'core/constants/app_constants.dart';
import 'routes/app_pages.dart';
import 'data/datasources/auth_datasource.dart';
import 'data/datasources/firestore_datasource.dart';
import 'data/datasources/quest_datasource.dart';
import 'data/datasources/activity_datasource.dart';
import 'data/repositories/auth_repository_impl.dart';
import 'data/repositories/user_profile_repository_impl.dart';
import 'data/repositories/quest_repository_impl.dart';
import 'data/repositories/activity_repository_impl.dart';
import 'features/auth/controllers/auth_controller.dart';
import 'features/quests/controllers/quest_controller.dart';
import 'features/profile/controllers/profile_controller.dart';
import 'package:firebase_auth/firebase_auth.dart';

void main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Initialize Firebase
  // Note: firebase_options.dart will be generated by flutterfire configure
  // Until then, the app will run without Firebase initialization
  try {
    await Firebase.initializeApp();
  } catch (e) {
    // Firebase not configured yet - app will run without Firebase
    debugPrint('Firebase not initialized: $e');
  }

  // Initialize dependencies
  final authRemoteDataSource = AuthRemoteDataSourceImpl(FirebaseAuth.instance);
  final authRepository = AuthRepositoryImpl(authRemoteDataSource);

  final firestoreRemoteDataSource = FirestoreRemoteDataSourceImpl(FirebaseFirestore.instance);
  final userProfileRepository = UserProfileRepositoryImpl(firestoreRemoteDataSource);

  final questRemoteDataSource = QuestRemoteDataSourceImpl(FirebaseFirestore.instance);
  final questRepository = QuestRepositoryImpl(questRemoteDataSource);

  final activityRemoteDataSource = ActivityRemoteDataSourceImpl(FirebaseFirestore.instance);
  final activityRepository = ActivityRepositoryImpl(activityRemoteDataSource);

  final authController = AuthController(authRepository, userProfileRepository);
  final questController = QuestController(
    questRepository,
    authController,
    userProfileRepository,
    activityRepository,
  );
  final profileController = ProfileController(userProfileRepository, authController);

  runApp(StudyQuestApp(
    authController: authController,
    questController: questController,
    profileController: profileController,
  ));
}

class StudyQuestApp extends StatelessWidget {
  final AuthController authController;
  final QuestController questController;
  final ProfileController profileController;

  const StudyQuestApp({
    super.key,
    required this.authController,
    required this.questController,
    required this.profileController,
  });

  @override
  Widget build(BuildContext context) {
    return GetMaterialApp(
      title: AppConstants.appName,
      theme: ThemeData(
        colorScheme: ColorScheme.fromSeed(seedColor: Colors.deepPurple),
        useMaterial3: true,
      ),
      initialRoute: AppPages.INITIAL,
      getPages: AppPages.routes,
      initialBinding: BindingsBuilder(() {
        Get.put(authController);
        Get.put(questController);
        Get.put(profileController);
      }),
    );
  }
}
